def decrypt(short_array, offset, length, key):
    result = []
    for i in range(length):
        idx = offset + i
        if idx < len(short_array):
            ch = short_array[idx] ^ key
            result.append(chr(ch & 0xFFFF))
        else:
            result.append('?')
    return ''.join(result)

