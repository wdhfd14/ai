import re

# Only look for strings that match common JSON key patterns
# (lowercase, underscores, camelCase)
word_pattern = re.compile(r'^[a-z][a-z_0-9]*$')

found = []
for offset in range(len(short_array)):
    for key in range(0x10000):
        # Check max length first
        max_len = 0
        for length in range(3, min(80, len(short_array) - offset + 1)):
            all_ascii = True
            for i in range(length):
                ch = short_array[offset + i] ^ key
                if ch < 0x20 or ch > 0x7e:
                    all_ascii = False
                    break
            if all_ascii:
                max_len = length
            else:
                break

        if max_len >= 3:
            result = decrypt(short_array, offset, max_len, key)
            # Filter: only keep strings that look like real words/keys
            lower = result.lower()
            if word_pattern.match(lower) and len(result) >= 3:
                found.append((offset, max_len, key, result))

# Deduplicate by string content
seen = set()
for offset, length, key, result in sorted(found, key=lambda x: (x[0], -x[1])):
    if result not in seen:
        seen.add(result)
        print(f"offset=0x{offset:x}({offset}), length={length}, key=0x{key:x} -> \"{result}\"")
