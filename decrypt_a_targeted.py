def decrypt(short_array, offset, length, key):
    """XOR decrypt: char[i] = short_array[offset + i] ^ key"""
    result = []
    for i in range(length):
        idx = offset + i
        if idx < len(short_array):
            ch = short_array[idx] ^ key
            result.append(chr(ch & 0xFFFF))
        else:
            result.append('?')
    return ''.join(result)

def xor32(a, b):
    """XOR two values as 32-bit signed integers"""
    result = (a ^ b) & 0xFFFFFFFF
    if result >= 0x80000000:
        result -= 0x100000000
    return result

