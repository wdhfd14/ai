def decrypt(arr, offset, length, xor_key):
    result = []
    for i in range(length):
        if offset + i >= len(arr):
            break
        val = arr[offset + i]
        decoded = (val ^ (xor_key & 0xFFFF)) & 0xFFFF
        result.append(chr(decoded))
    return ''.join(result)

